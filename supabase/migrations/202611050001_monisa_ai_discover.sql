-- Estrutura para conversas e mensagens da Monisa na Vercel.
-- Execute no SQL Editor do projeto Supabase antes de testar a IA.

create table if not exists public.study_conversations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null default 'Nova conversa',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists study_conversations_user_updated_idx
  on public.study_conversations (user_id, updated_at desc);

create table if not exists public.study_messages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  conversation_id bigint not null references public.study_conversations(id) on delete cascade,
  role text not null check (role in ('user', 'assistant')),
  content text not null,
  created_at timestamptz not null default now()
);

create index if not exists study_messages_conversation_idx
  on public.study_messages (user_id, conversation_id, id);

alter table public.study_conversations enable row level security;
alter table public.study_messages enable row level security;

drop policy if exists "Users manage own Monisa conversations" on public.study_conversations;
create policy "Users manage own Monisa conversations"
  on public.study_conversations for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users manage own Monisa messages" on public.study_messages;
create policy "Users manage own Monisa messages"
  on public.study_messages for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

grant select, insert, update, delete on public.study_conversations to authenticated;
grant select, insert, update, delete on public.study_messages to authenticated;
grant usage, select on all sequences in schema public to authenticated;
